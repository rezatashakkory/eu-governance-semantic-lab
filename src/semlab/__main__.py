"""Command line: python -m semlab <command>."""

import argparse
import sys

from semlab import load_all
from semlab.loading import ONTOLOGY_FILE, ROOT, load_graph
from semlab.queries import QueryError, list_queries, run_query
from semlab.serialization import build_dist, out_of_sync
from semlab.validation import validate_graph
from semlab.vocabulary import label, pending_review, short_name


def cmd_validate(_args) -> int:
    """Validate the data against the SHACL shapes. Exit code 1 means a violation."""
    result = validate_graph(load_all())
    for finding in result.findings:
        where = f" ({finding.path})" if finding.path else ""
        print(f"{finding.severity}: {short_name(finding.focus)}{where}: {finding.message}")
    print(
        f"SHACL: {'conforms' if result.conforms else 'DOES NOT CONFORM'}, "
        f"{len(result.violations)} violations, {len(result.warnings)} warnings"
    )
    return 0 if result.conforms else 1


def cmd_build(_args) -> int:
    """Generate JSON-LD and RDF/XML into data/dist and check they match the Turtle."""
    for path in build_dist():
        print("wrote", path.relative_to(ROOT).as_posix())
    problems = out_of_sync()
    for problem in problems:
        print("PROBLEM:", problem)
    return 1 if problems else 0


def cmd_check_dist(_args) -> int:
    problems = out_of_sync()
    for problem in problems:
        print("PROBLEM:", problem)
    print("dist: in sync" if not problems else "dist: OUT OF SYNC, run python -m semlab build")
    return 1 if problems else 0


def cmd_queries(args) -> int:
    """List the documented queries, or run one by number."""
    queries = list_queries()
    if not args.number:
        for q in queries:
            print(f"{q.number}  [{q.level}]  {q.title}")
        return 0
    chosen = next((q for q in queries if q.number == args.number.zfill(2)), None)
    if chosen is None:
        print(f"No query numbered {args.number}.", file=sys.stderr)
        return 2
    try:
        result = run_query(load_all(), chosen.text)
    except QueryError as error:
        print(error, file=sys.stderr)
        return 1
    print(f"{chosen.number}: {chosen.title}\n{chosen.purpose}\n")
    if result.kind == "select":
        print(" | ".join(result.columns))
        for row in result.rows:
            print(" | ".join(row))
    elif result.kind == "ask":
        print(result.boolean)
    else:
        print(result.graph.serialize(format="turtle"))
    return 0


def cmd_reason(_args) -> int:
    """Show what OWL RL reasoning adds to the data."""
    from semlab.reasoning import expand

    graph = load_all()
    _, inferred = expand(graph, load_graph(ONTOLOGY_FILE))
    print(f"{len(graph)} triples asserted, {len(inferred)} new triples inferred. First 15:")
    for s, p, o in sorted(inferred)[:15]:
        print(
            " ",
            graph.namespace_manager.normalizeUri(s),
            graph.namespace_manager.normalizeUri(p),
            graph.namespace_manager.normalizeUri(o),
        )
    return 0


def cmd_translations(_args) -> int:
    """Write docs/translations_to_review.md from the data."""
    graph = load_all()
    names = {"fr": "French", "de": "German"}
    lines = [
        "# Translations to review",
        "",
        "This file is generated by `python -m semlab translations`. Do not edit it by hand.",
        "",
        "Every French and German label below is marked `lab:pendingReview` in the thesaurus. "
        "Labels that were taken from EuroVoc are not listed. After a native speaker confirms a "
        "label, remove the language from `lab:pendingReview` on that concept in "
        "`data/vocabulary/eu-data-governance.ttl`.",
        "",
    ]
    for lang, concepts in pending_review(graph).items():
        lines += [
            f"## {names.get(lang, lang)} ({len(concepts)} concepts)",
            "",
            f"| Concept | English | {names.get(lang, lang)} |",
            "| --- | --- | --- |",
        ]
        for concept in concepts:
            lines.append(
                f"| `{short_name(concept)}` | {label(graph, concept, 'en')} | "
                f"{label(graph, concept, lang)} |"
            )
        lines.append("")
    target = ROOT / "docs" / "translations_to_review.md"
    target.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", target.relative_to(ROOT).as_posix())
    return 0


def cmd_verify_acts(_args) -> int:
    """Compare the dataset with the live Cellar endpoint. Needs internet access."""
    from semlab.cellar import CellarError, verify_dataset

    try:
        problems = verify_dataset(load_all())
    except CellarError as error:
        print(f"Could not verify: {error}", file=sys.stderr)
        return 2
    for problem in problems:
        print("MISMATCH:", problem)
    print("Cellar check: all acts match" if not problems else "Cellar check: mismatches found")
    return 1 if problems else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="semlab", description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("validate", help="SHACL validation of the data").set_defaults(func=cmd_validate)
    sub.add_parser("build", help="generate JSON-LD and RDF/XML in data/dist").set_defaults(
        func=cmd_build
    )
    sub.add_parser("check-dist", help="check generated files match the Turtle").set_defaults(
        func=cmd_check_dist
    )
    q = sub.add_parser("queries", help="list or run the documented SPARQL queries")
    q.add_argument("number", nargs="?", help="query number, for example 5")
    q.set_defaults(func=cmd_queries)
    sub.add_parser("reason", help="show OWL RL inferences").set_defaults(func=cmd_reason)
    sub.add_parser("translations", help="write the translation review list").set_defaults(
        func=cmd_translations
    )
    sub.add_parser("verify-acts", help="compare the acts with live Cellar data").set_defaults(
        func=cmd_verify_acts
    )
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
